'use client'

/**
 * The consultation screen (BUILD_ROADMAP C4, C6, C7).
 *
 * The whole flow on one page: write or photograph notes, generate, review
 * and correct the draft, save. Kept as its own component so the route stays
 * a thin server shell that only awaits `params`.
 *
 * THREE MUTUALLY EXCLUSIVE STATES, and the third is the one that matters:
 *   draft + aiNote       -> the editable review with its flags (C6)
 *   draft, no aiNote     -> save the free-text notes alone (E29, E23)
 *   confirmed            -> the read-only record, styled unlike the draft
 */
import { emptyStructuredNote } from '@emr/shared'
import { useQuery } from '@tanstack/react-query'
import { ArrowLeftIcon } from 'lucide-react'
import Link from 'next/link'
import { ConsultationComposer } from '@/components/consultation/consultation-composer'
import { DraftReviewPanel } from '@/components/consultation/draft-review-panel'
import { SaveConsultation } from '@/components/consultation/save-consultation'
import { StructuredNoteView } from '@/components/consultation/structured-note-view'
import {
  UnsavedWorkProvider,
  useConsultationGuard,
} from '@/components/consultation/unsaved-work-context'
import { ErrorState } from '@/components/states/error-state'
import { LoadingState } from '@/components/states/loading-state'
import { api, unwrap } from '@/lib/api'
import { formatDateShort } from '@/lib/format'

export function ConsultationView({ consultationId }: { consultationId: string }) {
  return (
    // F16 -- the provider wraps the whole screen so the header link below
    // can see dirtiness generated by components beside it, not under it.
    <UnsavedWorkProvider>
      <ConsultationScreen consultationId={consultationId} />
    </UnsavedWorkProvider>
  )
}

function ConsultationScreen({ consultationId }: { consultationId: string }) {
  const { isDirty, onNavigate } = useConsultationGuard()

  const { data, isPending, error, refetch } = useQuery({
    queryKey: ['consultation', consultationId],
    queryFn: async () => unwrap(await api.consultations({ id: consultationId }).get()),
  })

  if (isPending) {
    return (
      <main className="mx-auto w-full max-w-3xl px-6 py-10">
        <LoadingState rows={3} variant="form" label="Loading consultation" />
      </main>
    )
  }

  if (error) {
    return (
      <main className="mx-auto w-full max-w-3xl px-6 py-10">
        <ErrorState error={error} onRetry={() => void refetch()} />
      </main>
    )
  }

  const { consultation } = data
  const isConfirmed = consultation.status === 'confirmed'

  return (
    <main className="mx-auto w-full max-w-3xl px-6 py-10">
      {/*
        E26 -- the in-app exit. `onNavigate` is Next 16's hook for cancelling
        a client-side transition; `beforeunload` (in the guard hook) covers
        closing the tab. Neither sees the other's exit route, so both are
        needed.
      */}
      <Link
        href={`/patients/${consultation.patientId}`}
        onNavigate={onNavigate}
        className="mb-6 inline-flex items-center gap-1.5 rounded-sm text-muted-foreground text-sm hover:text-foreground focus-visible:outline-2 focus-visible:outline-ring focus-visible:outline-offset-2"
      >
        <ArrowLeftIcon className="size-3.5" aria-hidden="true" />
        Back to patient
      </Link>

      {/*
        Visible, not just a dialog on the way out. A doctor who can see that
        work is unsaved may never trigger the guard at all -- which is a
        better outcome than a prompt they have to read under time pressure.
      */}
      {isDirty && (
        <p className="mb-4 text-amber-700 text-xs" role="status">
          You have unsaved changes.
        </p>
      )}

      <header className="mb-6">
        <h1 className="font-semibold text-2xl tracking-tight">Consultation</h1>
        <p className="mt-1 text-muted-foreground text-sm">
          {formatDateShort(consultation.createdAt)}
          {isConfirmed ? ' · Saved' : ' · Draft'}
        </p>
      </header>

      {/*
        A confirmed consultation is immutable (the API returns 409 on a
        PATCH). Rendering it read-only means the doctor meets that rule as a
        disabled field rather than as a rejected save.
      */}
      <ConsultationComposer
        consultationId={consultationId}
        initialNotes={consultation.rawNotes}
        readOnly={isConfirmed}
      />

      {/* F5 + F6 -- the editable draft, its flags and the nudge (C6). */}
      {!isConfirmed && consultation.aiNote && (
        <div className="mt-8">
          <DraftReviewPanel
            consultationId={consultationId}
            appointmentId={consultation.appointmentId}
            patientId={consultation.patientId}
            aiNote={consultation.aiNote}
            verification={consultation.verification}
          />
        </div>
      )}

      {/*
        E29 + E23 -- SAVE WITHOUT AN AI NOTE AT ALL.
        "Free-text notes alone are a valid consultation."

        This is the path a doctor takes when the provider is down (§4.11's
        most important guardrail) or when they simply did not want to
        generate. Without it, the save button only exists beside an AI draft
        and the AI becomes a dependency for recording a visit -- exactly the
        coupling the whole degradation story exists to prevent.

        An empty structured note is saved: the raw notes carry the content,
        and inventing structured fields the doctor never approved would be
        the fabrication the rest of the system is built to avoid.
      */}
      {!isConfirmed && !consultation.aiNote && (
        <div className="mt-8 rounded-lg border bg-card p-4">
          <h2 className="mb-1 font-medium text-sm">Save without a structured note</h2>
          <p className="mb-3 text-muted-foreground text-sm">
            Your written notes are recorded as they are. You can generate a structured
            note first, but you do not have to.
          </p>
          <SaveConsultation
            consultationId={consultationId}
            appointmentId={consultation.appointmentId}
            patientId={consultation.patientId}
            note={emptyStructuredNote()}
          />
        </div>
      )}

      {/*
        F14 -- the confirmed note looks deliberately UNLIKE the draft: a
        solid border and no "not saved" badge. The visual distinction is the
        point, so the two must not share a container style.
      */}
      {isConfirmed && consultation.confirmedNote && (
        <section className="mt-8 rounded-lg border bg-card p-4">
          <h2 className="mb-3 font-medium text-sm">Saved note</h2>
          <StructuredNoteView note={consultation.confirmedNote} />
        </section>
      )}
    </main>
  )
}
